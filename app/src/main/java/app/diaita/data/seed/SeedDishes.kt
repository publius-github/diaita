package app.diaita.data.seed

/**
 * Seeded compositions for the Dishes tab: everyday home-cooked dishes as raw-ingredient
 * lists plus a typical cooked weight, so kcal/100 g is derived and every dish is logged
 * by weighing the eaten portion. These replace the flat per-100g prepared-dish rows the
 * food catalog used to ship ([SeedFoods.retired]) — a composition can be tuned to how
 * the user actually cooks, a flat number cannot.
 *
 * Ingredient weights are raw (pre-cooking) and reference [SeedFoods] entries by seedKey;
 * cooked weights include added water for soups and account for moisture loss in fried and
 * baked dishes. Proportions and yields are typical-recipe approximations, same standard
 * as the catalog's nutrition figures — the point is a sane starting composition the user
 * edits to match their own pot.
 *
 * Sync rules ([SeedDatabaseCallback]): a dish is inserted only while the stored dish
 * version is behind its [SeedDish.sinceVersion] — so a dish the user deleted is never
 * resurrected by a later app update; an existing unedited dish is refreshed in place; an
 * edited one ([app.diaita.data.db.entities.MealPreset.editedByUser]) is never touched.
 */
